from unittest import result

from dotenv import load_dotenv
import os
load_dotenv()

import streamlit as st
import sqlite3

import google.generativeai as genai
genai.configure(api_key=os.getenv("GENAI_API_KEY"))

# Function to load gemini model and priovide query as response 

def get_gemini_response(question,prompt):
    model =genai.GenerativeModel('gemini-3.8-flash')
    response = model.generate_content([prompt[0], question])
    return response.text
## function to retrieve query from the sqlite database and return the response to the user
def read_sql_query(sql,db):
    conn = sqlite3.connect(db)
    cursor = conn.cursor()
    cursor.execute(sql)
    rows = cursor.fetchall()
    conn.commit()
    conn.close()
    for row in rows:
        print(row)
    return rows


prompt=["""
        you are an expert in converting english questions to sql query! 
        the sql database has the namme STUDENTand has the following columns 
        NAME, CLASS, SECTION \n\nfor example,\n example 1- how many entitites 
        of record are present?,
        the sql command will be SELECT COUNT(*) FROM STUDENT;
        \n example 2- tell me all the students present in the data science class?,
        the sql command will be something like 
        SELECT * FROM STUDENT WHERE CLASS='Data Science';
        also the sql code should not have ''' in the begining or end and 
        query should not be in small letters"""]

## Streamlit app
st.set_page_config(page_title="Text to SQL LLM Application", page_icon=":guardsman:", layout="wide")
st.title("Text to SQL LLM Application")
st.write("This application uses Gemini Pro LLM to convert English questions to SQL queries and retrieve data from a SQLite database.")
st.header("Enter your question below:")
question=st.text_input('Input:',key='input')
submit=st.button('Ask the question')

## if submit is clicked
if submit:
    response = get_gemini_response(question,prompt)
    print("SQL Query generated by Gemini Pro LLM:", response)
    data = read_sql_query(response,'student.db')
    st.subheader("SQL Query generated by Gemini Pro LLM:")
    for row in data:
        print(row)
        st.header(row)